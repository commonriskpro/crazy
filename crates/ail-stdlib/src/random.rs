// ── DeterministicRng ──────────────────────────────────────────────────────

/// A simple Linear Congruential Generator (LCG) seeded deterministically.
///
/// Not suitable for security-sensitive use — use `CryptoRng` marker instead.
#[derive(Clone, Debug)]
pub struct DeterministicRng {
    state: u64,
}

impl DeterministicRng {
    /// Create a new RNG from the given seed.
    pub fn new(seed: Seed) -> Self {
        Self { state: seed.0 }
    }

    /// Advance the state and return the next `u64`.
    fn next_u64(&mut self) -> u64 {
        // Knuth multiplicative LCG (mod 2^64)
        self.state = self
            .state
            .wrapping_mul(6_364_136_223_846_793_005)
            .wrapping_add(1_442_695_040_888_963_407);
        self.state
    }

    /// Generate a random `i64` value.
    pub fn random_int(&mut self) -> i64 {
        self.next_u64() as i64
    }

    /// Generate a random `f64` in `[0.0, 1.0)`.
    pub fn random_float(&mut self) -> f64 {
        (self.next_u64() >> 11) as f64 / (1u64 << 53) as f64
    }

    /// Generate `n` random bytes.
    pub fn random_bytes(&mut self, n: usize) -> Vec<u8> {
        (0..n).map(|_| (self.next_u64() & 0xFF) as u8).collect()
    }

    /// Generate a random `i64` in the range `[min, max)`.
    pub fn random_int_range(&mut self, min: i64, max: i64) -> Option<i64> {
        if min >= max {
            return None;
        }
        let range = (max as i128) - (min as i128);
        let offset = (self.next_u64() as u128 % range as u128) as i128;
        Some((min as i128 + offset) as i64)
    }
}

// ── CryptoRng ─────────────────────────────────────────────────────────────

/// Marker for cryptographically-secure randomness.
///
/// Actual crypto-random byte generation requires the `crypto.random.bytes`
/// capability provided by the AIL runtime host. This type is the API surface;
/// the runtime binds the implementation.
#[derive(Debug)]
pub struct CryptoRng;

impl CryptoRng {
    /// Marker constructor. Runtime must inject capability.
    pub fn new() -> Self {
        Self
    }
}

impl Default for CryptoRng {
    fn default() -> Self {
        Self::new()
    }
}

// ── RandomBytes ───────────────────────────────────────────────────────────

/// A fixed-size array of random bytes.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RandomBytes(pub Vec<u8>);

impl RandomBytes {
    pub fn new(bytes: Vec<u8>) -> Self {
        Self(bytes)
    }
    pub fn len(&self) -> usize {
        self.0.len()
    }
    pub fn is_empty(&self) -> bool {
        self.0.is_empty()
    }
    pub fn as_slice(&self) -> &[u8] {
        &self.0
    }
}

// ── Tests ─────────────────────────────────────────────────────────────────

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn deterministic_range_handles_full_i64_domain_without_overflow() {
        let mut rng = DeterministicRng::new(Seed::new(42));

        let value = rng
            .random_int_range(i64::MIN, i64::MAX)
            .expect("full signed range should be representable");

        assert!(value < i64::MAX);
    }

    #[test]
    fn random_descriptors_are_capability_gated_and_redacted() {
        let deterministic = RandomOperationDescriptor::deterministic_bytes(Seed::new(7), 32);
        assert_eq!(deterministic.capability_label, "random.seeded");
        assert!(!deterministic.grant_required);
        assert!(!deterministic.ambient_access);
        assert!(deterministic.deterministic_replay);
        assert_eq!(
            deterministic.diagnostic_key(),
            "std.random.deterministic_bytes:random.seeded:non-zero:bounded:no-range"
        );

        let crypto = RandomOperationDescriptor::crypto_bytes(32);
        assert_eq!(crypto.capability_label, "crypto.random.bytes");
        assert!(crypto.grant_required);
        assert!(!crypto.ambient_access);
        assert!(!crypto.deterministic_replay);
        assert_eq!(
            crypto.diagnostic_key(),
            "std.random.crypto_bytes:crypto.random.bytes:no-seed:bounded:no-range"
        );
    }

    #[test]
    fn random_contract_validation_reports_shapes_without_values() {
        let oversized = RandomOperationDescriptor::crypto_bytes_with_limit(9, 8);
        let err = oversized
            .validate_shape()
            .expect_err("too-large byte count");
        assert_eq!(err.byte_count_shape, Some(RandomByteCountShape::TooLarge));
        assert_eq!(
            err.to_string(),
            "invalid random operation shape: kind=crypto_bytes, byte_count_shape=too-large"
        );

        let reversed = RandomOperationDescriptor::deterministic_int_range(Seed::new(99), 10, 10);
        let err = reversed.validate_shape().expect_err("empty range");
        assert_eq!(err.seed_shape, Some(RandomSeedShape::NonZero));
        assert_eq!(err.range_shape, Some(RandomRangeShape::EmptyOrReversed));
        assert_eq!(
            err.to_string(),
            "invalid random operation shape: kind=deterministic_int_range, seed_shape=non-zero, range_shape=empty-or-reversed"
        );
    }
}
