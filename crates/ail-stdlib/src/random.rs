// ── ail-stdlib::random ────────────────────────────────────────────────────
//
// Seeded random generation for the AIL `std.random` module.
//
// # Rules (from docs/stdlib.md)
//
// - randomness is not pure
// - deterministic and crypto randomness are separate
//
// Deterministic: LCG seeded by caller.
// Crypto: type-level marker only (actual crypto random bytes require
//   the `crypto.random.bytes` capability provided by the runtime).

// ── Random capability contracts ──────────────────────────────────────────

/// Runtime capability labels exposed by `std.random` operations.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RandomCapability {
    /// Deterministic RNG seeded by the caller; no host entropy grant needed.
    DeterministicSeed,
    /// Cryptographically secure random bytes provided by the host.
    CryptoBytes,
}

impl RandomCapability {
    pub fn label(self) -> &'static str {
        match self {
            RandomCapability::DeterministicSeed => "random.seeded",
            RandomCapability::CryptoBytes => "crypto.random.bytes",
        }
    }
}

impl std::fmt::Display for RandomCapability {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.label())
    }
}

/// Stable operation families for random generation.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RandomOperationKind {
    DeterministicInt,
    DeterministicFloat,
    DeterministicBytes,
    DeterministicIntRange,
    CryptoBytes,
}

impl RandomOperationKind {
    pub fn label(self) -> &'static str {
        match self {
            RandomOperationKind::DeterministicInt => "deterministic_int",
            RandomOperationKind::DeterministicFloat => "deterministic_float",
            RandomOperationKind::DeterministicBytes => "deterministic_bytes",
            RandomOperationKind::DeterministicIntRange => "deterministic_int_range",
            RandomOperationKind::CryptoBytes => "crypto_bytes",
        }
    }

    pub fn required_capability(self) -> RandomCapability {
        match self {
            RandomOperationKind::CryptoBytes => RandomCapability::CryptoBytes,
            RandomOperationKind::DeterministicInt
            | RandomOperationKind::DeterministicFloat
            | RandomOperationKind::DeterministicBytes
            | RandomOperationKind::DeterministicIntRange => RandomCapability::DeterministicSeed,
        }
    }

    pub fn grant_required(self) -> bool {
        matches!(self, RandomOperationKind::CryptoBytes)
    }
}

/// Redacted seed taxonomy. Diagnostics expose shape, never seed material.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RandomSeedShape {
    Zero,
    NonZero,
}

impl RandomSeedShape {
    pub fn label(self) -> &'static str {
        match self {
            RandomSeedShape::Zero => "zero",
            RandomSeedShape::NonZero => "non-zero",
        }
    }
}

/// Redacted byte-count taxonomy for random byte requests.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RandomByteCountShape {
    Empty,
    Bounded,
    TooLarge,
}

impl RandomByteCountShape {
    pub fn label(self) -> &'static str {
        match self {
            RandomByteCountShape::Empty => "empty",
            RandomByteCountShape::Bounded => "bounded",
            RandomByteCountShape::TooLarge => "too-large",
        }
    }

    pub fn is_allowed(self) -> bool {
        !matches!(self, RandomByteCountShape::TooLarge)
    }
}

/// Stable shape for integer range requests.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RandomRangeShape {
    Ascending,
    EmptyOrReversed,
}

impl RandomRangeShape {
    pub fn label(self) -> &'static str {
        match self {
            RandomRangeShape::Ascending => "ascending",
            RandomRangeShape::EmptyOrReversed => "empty-or-reversed",
        }
    }

    pub fn is_allowed(self) -> bool {
        matches!(self, RandomRangeShape::Ascending)
    }
}

/// Redacted random contract error. Does not echo seeds or generated bytes.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RandomShapeError {
    pub kind: RandomOperationKind,
    pub seed_shape: Option<RandomSeedShape>,
    pub byte_count_shape: Option<RandomByteCountShape>,
    pub range_shape: Option<RandomRangeShape>,
}

impl std::fmt::Display for RandomShapeError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            f,
            "invalid random operation shape: kind={}",
            self.kind.label()
        )?;
        if let Some(shape) = self.seed_shape {
            write!(f, ", seed_shape={}", shape.label())?;
        }
        if let Some(shape) = self.byte_count_shape {
            write!(f, ", byte_count_shape={}", shape.label())?;
        }
        if let Some(shape) = self.range_shape {
            write!(f, ", range_shape={}", shape.label())?;
        }
        Ok(())
    }
}

impl std::error::Error for RandomShapeError {}

/// Deny-by-default descriptor for a `std.random` operation.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct RandomOperationDescriptor {
    pub kind: RandomOperationKind,
    pub capability: RandomCapability,
    pub capability_label: &'static str,
    pub seed_shape: Option<RandomSeedShape>,
    pub byte_count_shape: Option<RandomByteCountShape>,
    pub range_shape: Option<RandomRangeShape>,
    pub grant_required: bool,
    pub ambient_access: bool,
    pub deterministic_replay: bool,
}

impl RandomOperationDescriptor {
    pub const DEFAULT_MAX_BYTES: usize = 1 << 20;

    pub fn deterministic_int(seed: Seed) -> Self {
        Self::new(
            RandomOperationKind::DeterministicInt,
            Some(seed),
            None,
            None,
            None,
            None,
        )
    }

    pub fn deterministic_float(seed: Seed) -> Self {
        Self::new(
            RandomOperationKind::DeterministicFloat,
            Some(seed),
            None,
            None,
            None,
            None,
        )
    }

    pub fn deterministic_bytes(seed: Seed, count: usize) -> Self {
        Self::new(
            RandomOperationKind::DeterministicBytes,
            Some(seed),
            Some(count),
            None,
            None,
            None,
        )
    }

    pub fn deterministic_int_range(seed: Seed, min: i64, max: i64) -> Self {
        Self::new(
            RandomOperationKind::DeterministicIntRange,
            Some(seed),
            None,
            Some(min),
            Some(max),
            None,
        )
    }

    pub fn crypto_bytes(count: usize) -> Self {
        Self::new(
            RandomOperationKind::CryptoBytes,
            None,
            Some(count),
            None,
            None,
            None,
        )
    }

    pub fn crypto_bytes_with_limit(count: usize, max_bytes: usize) -> Self {
        Self::new(
            RandomOperationKind::CryptoBytes,
            None,
            Some(count),
            None,
            None,
            Some(max_bytes),
        )
    }

    fn new(
        kind: RandomOperationKind,
        seed: Option<Seed>,
        count: Option<usize>,
        range_min: Option<i64>,
        range_max: Option<i64>,
        max_bytes: Option<usize>,
    ) -> Self {
        let capability = kind.required_capability();
        Self {
            kind,
            capability,
            capability_label: capability.label(),
            seed_shape: seed.map(random_seed_shape),
            byte_count_shape: count.map(|count| {
                random_byte_count_shape(count, max_bytes.unwrap_or(Self::DEFAULT_MAX_BYTES))
            }),
            range_shape: range_min
                .zip(range_max)
                .map(|(min, max)| random_range_shape(min, max)),
            grant_required: kind.grant_required(),
            ambient_access: false,
            deterministic_replay: capability == RandomCapability::DeterministicSeed,
        }
    }

    pub fn diagnostic_key(&self) -> String {
        let seed_shape = self
            .seed_shape
            .map(RandomSeedShape::label)
            .unwrap_or("no-seed");
        let byte_count_shape = self
            .byte_count_shape
            .map(RandomByteCountShape::label)
            .unwrap_or("no-bytes");
        let range_shape = self
            .range_shape
            .map(RandomRangeShape::label)
            .unwrap_or("no-range");
        format!(
            "std.random.{}:{}:{}:{}:{}",
            self.kind.label(),
            self.capability_label,
            seed_shape,
            byte_count_shape,
            range_shape
        )
    }

    pub fn validate_shape(&self) -> Result<(), RandomShapeError> {
        if self
            .byte_count_shape
            .map_or(false, |shape| !shape.is_allowed())
            || self.range_shape.map_or(false, |shape| !shape.is_allowed())
        {
            Err(RandomShapeError {
                kind: self.kind,
                seed_shape: self.seed_shape,
                byte_count_shape: self.byte_count_shape,
                range_shape: self.range_shape,
            })
        } else {
            Ok(())
        }
    }
}

pub fn random_seed_shape(seed: Seed) -> RandomSeedShape {
    if seed.0 == 0 {
        RandomSeedShape::Zero
    } else {
        RandomSeedShape::NonZero
    }
}

pub fn random_byte_count_shape(count: usize, max_bytes: usize) -> RandomByteCountShape {
    if count == 0 {
        RandomByteCountShape::Empty
    } else if count > max_bytes {
        RandomByteCountShape::TooLarge
    } else {
        RandomByteCountShape::Bounded
    }
}

pub fn random_range_shape(min: i64, max: i64) -> RandomRangeShape {
    if min < max {
        RandomRangeShape::Ascending
    } else {
        RandomRangeShape::EmptyOrReversed
    }
}

